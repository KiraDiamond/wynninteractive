function normalizeWhitespace(value) {
  return String(value ?? "").replace(/\u00a0/g, " ").replace(/\s+/g, " ").trim();
}

function splitLines(text) {
  return String(text ?? "").replace(/\r/g, "").split("\n").map((line) => line.trimEnd());
}

function sectionText(lines, heading) {
  const start = lines.findIndex((line) => normalizeWhitespace(line) === heading);
  if (start < 0) {
    return [];
  }

  const afterHeading = start + 1;
  let end = lines.length;
  for (let index = afterHeading; index < lines.length; index += 1) {
    const value = normalizeWhitespace(lines[index]);
    if (!value) {
      continue;
    }
    if (index > afterHeading && CAMP_CONFIG.some((camp) => camp.heading === value)) {
      end = index;
      break;
    }
    if (index > afterHeading && /^(New Lootrun Camps|🏠 Builds|📍|🧠|💰|🎯|🚩|🗺️)\b/i.test(value)) {
      end = index;
      break;
    }
  }

  return lines.slice(afterHeading, end);
}

function cleanParagraphs(lines) {
  const paragraphs = [];
  let current = [];

  for (const rawLine of lines) {
    const line = normalizeWhitespace(rawLine);
    if (!line || /^_+$/.test(line) || /^WATCH OUT FOR THESE/i.test(line)) {
      if (current.length) {
        paragraphs.push(normalizeWhitespace(current.join(" ")));
        current = [];
      }
      continue;
    }
    if (/^\*/.test(line)) {
      if (current.length) {
        paragraphs.push(normalizeWhitespace(current.join(" ")));
        current = [];
      }
      continue;
    }
    current.push(line);
  }

  if (current.length) {
    paragraphs.push(normalizeWhitespace(current.join(" ")));
  }

  return paragraphs.filter(Boolean);
}

function extractHazards(lines) {
  return lines
    .map((line) => normalizeWhitespace(line))
    .filter((line) => /^\*\s+.+\s+-\s+(?:Slay|Spelunk|Defense|Destroy|Target)/i.test(line))
    .map((line) => normalizeWhitespace(line.replace(/^\*\s*/, "").replace(/\s+-\s+.*$/, "")))
    .filter(Boolean)
    .slice(0, 6);
}

function buildExplanation(paragraphs, hazards) {
  const sections = [];

  if (paragraphs.length) {
    sections.push([
      "Overview",
      ...paragraphs
        .filter((paragraph) => !/masochist/i.test(paragraph))
        .slice(0, 2)
        .map((paragraph) => `• ${paragraph}`),
    ].join("\n"));
  }

  sections.push([
    "Unlock & Access",
    "• Unlock camps by clearing the related area quests and caves.",
    "• Quest completion is shared across classes, but cave completion is class-specific.",
    "• Each camp has its own daily bonus, so rotating camps can speed up syndicate progression.",
  ].join("\n"));

  if (hazards.length) {
    sections.push([
      "Common Trouble Spots",
      ...hazards.map((hazard) => `• ${hazard}`),
    ].join("\n"));
  }

  sections.push([
    "Notes",
    "• This guide text is intentionally descriptive rather than route-by-route so it stays useful as lootrun meta shifts.",
  ].join("\n"));

  return sections.join("\n\n");
}

async function main() {
  const raw = await fs.readFile(INPUT_PATH, "utf8");
  const lines = splitLines(raw);

  const content = Object.fromEntries(
    CAMP_CONFIG.map((camp) => {
      const section = sectionText(lines, camp.heading);
      const paragraphs = cleanParagraphs(section);
      const hazards = extractHazards(section);
      const summary = paragraphs[0] || `${camp.title} lootrun camp overview.`;

      return [
        camp.id,
        {
          summary,
          explanation: buildExplanation(paragraphs, hazards),
          sourceUrl: SOURCE_URL,
          tutorials: [],
        },
      ];
    }),
  );

  const file = [
    "// Generated by scripts/build-lootrun-camp-content.mjs",
    `// Source: ${INPUT_PATH}`,
    "",
    `export const GENERATED_LOOTRUN_CAMP_CONTENT = ${JSON.stringify(content, null, 2)};`,
    "",
  ].join("\n");

  await fs.writeFile(OUTPUT_PATH, file, "utf8");

  console.log(JSON.stringify({
    output: path.relative(ROOT, OUTPUT_PATH).replace(/\\/g, "/"),
    records: Object.keys(content).length,
  }, null, 2));
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
