import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright-core";
import { WIKI_MAP_MARKERS } from "../data/wiki-map-markers.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const PLAYLIST_URL =
  "https://www.youtube.com/watch?v=HmOi7fcXBWs&list=PLc80zKNTp_boHpFnXTTcls68nyEscq1pG&pp=0gcJCdAEOCosWNin";
const OUTPUT_PATH = path.join(ROOT, "data", "generated-quest-video-links.js");
const SUMMARY_PATH = path.join(ROOT, "data", "wiki-scrape", "quest-video-links", "summary.md");
const CHROME_CANDIDATES = [
  "C:/Program Files/Google/Chrome/Application/chrome.exe",
  "C:/Program Files (x86)/Google/Chrome/Application/chrome.exe",
  "C:/Program Files/Microsoft/Edge/Application/msedge.exe",
  "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
];

const TITLE_ALIASES = new Map([
  ["hero of gavel", "the hero of gavel"],
  ["ultimate questionmark quest guide wynncraft", "questionmark"],
  ["questionmark", "questionmark"],
]);

function normalizeTitle(value) {
  const base = String(value ?? "")
    .toLowerCase()
    .replace(/\s+-\s+wynncraft quest guide(?:\s*\[updated\])?$/i, "")
    .replace(/^ultimate\s+"?\?{3}"?\s+quest guide\s+-\s+wynncraft!?$/i, "???")
    .replace(/\[rol\s*\d+\]\s*/gi, "")
    .replace(/realm of light\s*[ivx]+\s*-\s*/gi, "")
    .replace(/['’]/g, "")
    .replace(/\?/g, "questionmark")
    .replace(/\bpart\s+1\b/g, "part i")
    .replace(/\bpart\s+2\b/g, "part ii")
    .replace(/\bpart\s+3\b/g, "part iii")
    .replace(/\bpart\s+4\b/g, "part iv")
    .replace(/\bpart\s+5\b/g, "part v")
    .replace(/[^a-z0-9]+/g, " ")
    .replace(/^the\s+/, "")
    .replace(/\s+/g, " ")
    .trim();

  return TITLE_ALIASES.get(base) || base;
}

function stripQuestGuideSuffix(title) {
  return String(title ?? "")
    .replace(/\s+-\s+Wynncraft Quest Guide(?:\s*\[UPDATED\])?$/i, "")
    .replace(/^ULTIMATE\s+"?\?{3}"?\s+QUEST GUIDE\s+-\s+Wynncraft!?$/i, "???")
    .trim();
}

async function resolveChromePath() {
  for (const candidate of CHROME_CANDIDATES) {
    try {
      await fs.access(candidate);
      return candidate;
    } catch {
      // Keep trying candidates.
    }
  }
  throw new Error("Could not find a local Chrome/Edge executable for playlist scraping.");
}

async function scrapePlaylist() {
  const executablePath = await resolveChromePath();
  const browser = await chromium.launch({ executablePath, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 2200 } });

  await page.goto(PLAYLIST_URL, { waitUntil: "domcontentloaded", timeout: 120000 });
  await page.waitForTimeout(4000);

  for (let i = 0; i < 35; i += 1) {
    await page.evaluate(() => {
      const panel = document.querySelector("ytd-playlist-panel-renderer #items");
      if (panel) {
        panel.scrollTop = panel.scrollHeight;
      }
    });
    await page.waitForTimeout(350);
  }

  const rows = await page.evaluate(() =>
    [...document.querySelectorAll("ytd-playlist-panel-video-renderer")]
      .map((row) => {
        const titleAnchor = row.querySelector("#video-title");
        const title = titleAnchor?.textContent?.trim() || "";
        const href = titleAnchor?.href || row.querySelector("a[href*='watch?']")?.href || "";
        return { title, href };
      })
      .filter((item) => item.title && item.href)
  );

  await browser.close();
  return rows;
}

function matchPlaylistRows(rows) {
  const questMarkers = WIKI_MAP_MARKERS.filter((item) => item.category === "quests");
  const markerByNormalizedTitle = new Map();

  for (const marker of questMarkers) {
    const normalized = normalizeTitle(marker.title);
    if (!markerByNormalizedTitle.has(normalized)) {
      markerByNormalizedTitle.set(normalized, []);
    }
    markerByNormalizedTitle.get(normalized).push(marker);
  }

  const matched = [];
  const unmatched = [];
  const seenMarkerIds = new Set();

  for (const row of rows) {
    const questTitle = stripQuestGuideSuffix(row.title);
    const normalized = normalizeTitle(questTitle);
    const candidates = markerByNormalizedTitle.get(normalized) || [];

    if (candidates.length !== 1) {
      unmatched.push({
        playlistTitle: row.title,
        questTitle,
        href: row.href,
        candidates: candidates.map((item) => item.title),
      });
      continue;
    }

    const marker = candidates[0];
    if (seenMarkerIds.has(marker.id)) {
      continue;
    }

    seenMarkerIds.add(marker.id);
    matched.push({
      markerId: marker.id,
      markerTitle: marker.title,
      playlistTitle: row.title,
      href: row.href,
    });
  }

  return { matched, unmatched };
}

async function writeOutputs({ matched, unmatched }) {
  const objectLiteral = Object.fromEntries(matched.map((item) => [item.markerId, { tutorials: [item.href] }]));

  const moduleText = [
    `// Generated by scripts/build-quest-video-links.mjs from ${PLAYLIST_URL}`,
    "",
    `export const GENERATED_QUEST_VIDEO_LINKS = ${JSON.stringify(objectLiteral, null, 2)};`,
    "",
  ].join("\n");

  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, moduleText, "utf8");

  const summaryLines = [
    "# Quest Video Links",
    "",
    `- Playlist URL: ${PLAYLIST_URL}`,
    `- Current quest markers matched: ${matched.length}`,
    `- Playlist rows left unmatched: ${unmatched.length}`,
    "",
    "## Unmatched Rows",
    "",
    ...unmatched.map((item) => `- ${item.questTitle}`),
    "",
  ];

  await fs.mkdir(path.dirname(SUMMARY_PATH), { recursive: true });
  await fs.writeFile(SUMMARY_PATH, summaryLines.join("\n"), "utf8");
}

async function main() {
  const rows = await scrapePlaylist();
  const { matched, unmatched } = matchPlaylistRows(rows);
  await writeOutputs({ matched, unmatched });

  console.log(
    JSON.stringify(
      {
        playlistRows: rows.length,
        matched: matched.length,
        unmatched: unmatched.length,
        output: path.relative(ROOT, OUTPUT_PATH).replace(/\\/g, "/"),
        summary: path.relative(ROOT, SUMMARY_PATH).replace(/\\/g, "/"),
      },
      null,
      2
    )
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
