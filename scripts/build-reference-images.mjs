import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { MARKER_CONTENT } from "../data/marker-content.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const OUTPUT_DIR = path.join(ROOT, "assets", "reference-images");
const MODULE_PATH = path.join(ROOT, "data", "reference-images.js");
const WIDTH_TARGET = 1200;
const CONCURRENCY = 6;

function dedupe(values) {
  return [...new Set(values.filter(Boolean))];
}

function expandReferenceUrl(url) {
  try {
    const parsed = new URL(url);

    if (/^(?:wynncraft|commons)\.wiki\.gg$/i.test(parsed.hostname)) {
      parsed.pathname = parsed.pathname.replace(/\/thumb\/(.+?)\/\d+px-([^/]+)$/i, "/thumb/$1/" + `${WIDTH_TARGET}px-$2`);
      return parsed.toString();
    }

    if (/static\.wikia\.nocookie\.net$/i.test(parsed.hostname)) {
      parsed.pathname = parsed.pathname.replace(/\/revision\/latest\/scale-to-width-down\/\d+/i, `/revision/latest/scale-to-width-down/${WIDTH_TARGET}`);
      return parsed.toString();
    }

    return parsed.toString();
  } catch {
    return url;
  }
}

function fileExtension(url, contentType) {
  const fromType = {
    "image/png": ".png",
    "image/jpeg": ".jpg",
    "image/webp": ".webp",
    "image/gif": ".gif",
    "image/svg+xml": ".svg",
  }[String(contentType || "").split(";")[0].trim().toLowerCase()];

  if (fromType) {
    return fromType;
  }

  try {
    const pathname = new URL(url).pathname;
    const ext = path.extname(pathname);
    return ext || ".img";
  } catch {
    return ".img";
  }
}

function hashName(url) {
  return crypto.createHash("sha1").update(url).digest("hex");
}

async function ensureDir(dir) {
  await fs.mkdir(dir, { recursive: true });
}

async function downloadImage(originalUrl) {
  const expandedUrl = expandReferenceUrl(originalUrl);
  const response = await fetch(expandedUrl, {
    headers: {
      "user-agent": "WynnAtlas/1.0 (+local reference image cache)",
    },
  });

  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText}`);
  }

  const contentType = response.headers.get("content-type") || "";
  const extension = fileExtension(expandedUrl, contentType);
  const fileName = `${hashName(expandedUrl)}${extension}`;
  const outputPath = path.join(OUTPUT_DIR, fileName);
  const bytes = Buffer.from(await response.arrayBuffer());
  await fs.writeFile(outputPath, bytes);

  return {
    originalUrl,
    expandedUrl,
    fileName,
  };
}

async function runPool(items, worker, concurrency) {
  const results = [];
  let index = 0;

  async function next() {
    while (index < items.length) {
      const current = index;
      index += 1;
      results[current] = await worker(items[current], current);
    }
  }

  await Promise.all(Array.from({ length: Math.min(concurrency, items.length) }, () => next()));
  return results;
}

async function main() {
  const urls = dedupe(
    Object.values(MARKER_CONTENT).flatMap((entry) => [
      entry.coverImage || "",
      ...(entry.gallery || []),
    ]),
  );

  await ensureDir(OUTPUT_DIR);

  const successes = [];
  const failures = [];

  await runPool(urls, async (url) => {
    try {
      const result = await downloadImage(url);
      successes.push(result);
    } catch (error) {
      failures.push({
        url,
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }, CONCURRENCY);

  const mapping = Object.fromEntries(
    successes.map(({ originalUrl, fileName }) => [
      originalUrl,
      `new URL("../assets/reference-images/${fileName}", import.meta.url).href`,
    ]),
  );

  const lines = [
    "// Generated by scripts/build-reference-images.mjs",
    "",
    "export const REFERENCE_IMAGE_URLS = {",
    ...Object.entries(mapping).map(([key, value]) => `  ${JSON.stringify(key)}: ${value},`),
    "};",
    "",
  ];

  await fs.writeFile(MODULE_PATH, lines.join("\n"), "utf8");

  console.log(JSON.stringify({
    total: urls.length,
    cached: successes.length,
    failed: failures.length,
    outputDir: path.relative(ROOT, OUTPUT_DIR).replace(/\\/g, "/"),
    module: path.relative(ROOT, MODULE_PATH).replace(/\\/g, "/"),
    failures: failures.slice(0, 20),
  }, null, 2));
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
